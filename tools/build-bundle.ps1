# Packs every module under script/ into script/Bundle/PartN.lua.
#
# Init reads Manifest.lua for the part count, fetches the parts a few at a time
# and decodes them with a frame in between, instead of asking the executor for
# ~77 separate downloads (whose queue stalled) or for one 1.5 MB file (which
# froze the client for 10-20 s while it arrived).
#
# Re-run this after changing any module under script/ and commit the result,
# otherwise a run picks up the previous build of the files it packs:
#
#   powershell -ExecutionPolicy Bypass -File tools/build-bundle.ps1
#
# PART_KB is the size each part is allowed to reach. Smaller parts mean shorter
# stalls; more of them means more requests. ~100 KB is one quick request.

param(
    [int]$PartKB = 100
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$scriptDir = Join-Path $root "script"
$outDir = Join-Path $scriptDir "Bundle"
$limit = $PartKB * 1024

$skip = @("Init.lua", "Bundle.lua")
$files = Get-ChildItem -Path $scriptDir -Recurse -Filter *.lua |
    Where-Object { $skip -notcontains $_.Name -and $_.DirectoryName -ne $outDir } |
    Sort-Object FullName

# The window library goes first and therefore ends up alone in Part1: the
# loader puts the window up as soon as that part is here, while the rest of the
# bundle is still downloading.
$seedPath = Join-Path (Join-Path $scriptDir "UI") "Utils.lua"
$files = @($files | Where-Object { $_.FullName -eq $seedPath }) + @($files | Where-Object { $_.FullName -ne $seedPath })

if (Test-Path $outDir) {
    Remove-Item $outDir -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$encoding = New-Object System.Text.UTF8Encoding($false)
$builder = New-Object System.Text.StringBuilder
$part = 0
$count = 0
$partBytes = 0

function Start-Part {
    $script:part++
    $script:builder = New-Object System.Text.StringBuilder
    [void]$script:builder.AppendLine("-- Generated by tools/build-bundle.ps1 - do not edit by hand.")
    [void]$script:builder.AppendLine("return {")
    $script:partBytes = 0
}

function Save-Part {
    [void]$script:builder.AppendLine("}")
    $path = Join-Path $outDir ("Part{0}.lua" -f $script:part)
    [System.IO.File]::WriteAllText($path, $script:builder.ToString(), $script:encoding)
}

Start-Part

foreach ($file in $files) {
    $relative = $file.FullName.Substring($scriptDir.Length + 1).Replace('\', '/')
    $source = [System.IO.File]::ReadAllText($file.FullName)

    if ($source.Contains("]======]")) {
        throw "$relative contains the bundle's long-bracket delimiter"
    }

    if ($partBytes -gt 0 -and ($partBytes + $source.Length) -gt $limit) {
        Save-Part
        Start-Part
    }

    [void]$builder.AppendLine("`t[""$relative""] = [======[")
    [void]$builder.Append($source)
    [void]$builder.AppendLine("]======],")
    $partBytes += $source.Length
    $count++
}

Save-Part

# Manifest tells the loader how many parts there are, so it fetches exactly
# those instead of probing for the end of the set one 404 at a time.
[System.IO.File]::WriteAllText((Join-Path $outDir "Manifest.lua"), "return { Parts = $part }`n", $encoding)

$total = [math]::Round((Get-ChildItem $outDir -Filter *.lua | Measure-Object Length -Sum).Sum / 1KB)
Write-Host "Wrote $part parts into script/Bundle ($count modules, $total KB)"
