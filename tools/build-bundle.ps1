# Packs every module under script/ into script/Bundle.lua, one table of
# path -> source. Init fetches that single file instead of asking the executor
# for ~77 separate downloads, which is what stalled its HTTP queue.
#
# Re-run this after changing any module under script/ and commit the result,
# otherwise a run picks up the previous build of the files it packs:
#
#   powershell -ExecutionPolicy Bypass -File tools/build-bundle.ps1

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$scriptDir = Join-Path $root "script"
$bundlePath = Join-Path $scriptDir "Bundle.lua"

$skip = @("Init.lua", "Bundle.lua")
$files = Get-ChildItem -Path $scriptDir -Recurse -Filter *.lua |
    Where-Object { $skip -notcontains $_.Name } |
    Sort-Object FullName

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine("-- Generated by tools/build-bundle.ps1 - do not edit by hand.")
[void]$builder.AppendLine("-- One request replaces the per-module downloads Init used to make.")
[void]$builder.AppendLine("return {")

$count = 0

foreach ($file in $files) {
    $relative = $file.FullName.Substring($scriptDir.Length + 1).Replace('\', '/')
    $source = [System.IO.File]::ReadAllText($file.FullName)

    if ($source.Contains("]======]")) {
        throw "$relative contains the bundle's long-bracket delimiter"
    }

    [void]$builder.AppendLine("`t[""$relative""] = [======[")
    [void]$builder.Append($source)
    [void]$builder.AppendLine("]======],")
    $count++
}

[void]$builder.AppendLine("}")

[System.IO.File]::WriteAllText($bundlePath, $builder.ToString(), (New-Object System.Text.UTF8Encoding($false)))

$size = [math]::Round((Get-Item $bundlePath).Length / 1KB)
Write-Host "Wrote $bundlePath ($count modules, $size KB)"
